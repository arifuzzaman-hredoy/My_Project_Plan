import { categoryLabels } from "./categories";
import { CategoryId, Certificate, Localized } from "./types";

const l = (en: string, bn = en): Localized => ({ en, bn });

const cert = (
  id: string,
  title: string,
  categoryId: CategoryId,
  level: Localized,
  priority: number,
  minOrBest: Certificate["minOrBest"],
  targetYear: Certificate["targetYear"],
  status: Certificate["status"],
  options: Partial<
    Pick<Certificate, "provider" | "cost" | "validity" | "proofType" | "notes">
  > = {},
): Certificate => ({
  id,
  title: l(title),
  categoryId,
  categoryLabel: categoryLabels[categoryId],
  level,
  priority,
  minOrBest,
  targetYear,
  status,
  provider: options.provider ?? "Official provider",
  cost: options.cost ?? "Varies",
  validity: options.validity ?? "Check official validity",
  proofType:
    options.proofType ??
    l("Certificate / score report", "Certificate / score report"),
  notes:
    options.notes ??
    l(
      `${title} strengthens the ${categoryLabels[categoryId].en} profile when stored with proof link and reflection.`,
      `${title} ${categoryLabels[categoryId].bn} profile strong করে, যদি proof link আর reflection সহ save করা হয়।`,
    ),
});

